-- HUMAN RHYTHMS v0.2 — Supabase PostgreSQL schema
-- Apply in Supabase SQL Editor. This schema is suitable for authenticated users.
-- The Streamlit starter currently supports a local single-user workflow and a
-- basic Supabase connection mode. Before public multi-user use, add Supabase Auth
-- sign-in and set profile_id from auth.uid() (never from a user-editable field).

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  birth_date date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.observations (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  observed_at timestamptz not null,
  domain text not null,
  indicator text not null,
  value double precision not null,
  unit text,
  scale_min double precision,
  scale_max double precision,
  source text not null default 'self_report',
  confidence integer check (confidence between 1 and 5),
  notes text,
  created_at timestamptz not null default now()
);
create index if not exists observations_profile_time_idx on public.observations(profile_id, observed_at);
create index if not exists observations_profile_indicator_idx on public.observations(profile_id, indicator);

create table if not exists public.life_periods (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  label text not null,
  start_date date not null,
  end_date date,
  description text,
  recall_confidence integer check (recall_confidence between 1 and 5),
  source text not null default 'retrospective_self_report',
  created_at timestamptz not null default now(),
  check (end_date is null or end_date >= start_date)
);
create index if not exists life_periods_profile_start_idx on public.life_periods(profile_id, start_date);

create table if not exists public.life_events (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  event_date date not null,
  title text not null,
  category text,
  description text,
  impact_domains jsonb not null default '[]'::jsonb,
  recall_confidence integer check (recall_confidence between 1 and 5),
  source text not null default 'retrospective_self_report',
  created_at timestamptz not null default now()
);
create index if not exists life_events_profile_date_idx on public.life_events(profile_id, event_date);

create table if not exists public.activities (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  activity_date date not null,
  activity text not null,
  category text,
  duration_minutes integer check (duration_minutes is null or duration_minutes >= 0),
  notes text,
  created_at timestamptz not null default now()
);
create index if not exists activities_profile_date_idx on public.activities(profile_id, activity_date);

-- Enable row-level security on every personal-data table.
alter table public.profiles enable row level security;
alter table public.observations enable row level security;
alter table public.life_periods enable row level security;
alter table public.life_events enable row level security;
alter table public.activities enable row level security;

-- A user can access only rows whose profile_id is their authenticated UUID.
drop policy if exists "profile owner access" on public.profiles;
create policy "profile owner access" on public.profiles
for all using (id = auth.uid()) with check (id = auth.uid());

drop policy if exists "observations owner access" on public.observations;
create policy "observations owner access" on public.observations
for all using (profile_id = auth.uid()) with check (profile_id = auth.uid());

drop policy if exists "life periods owner access" on public.life_periods;
create policy "life periods owner access" on public.life_periods
for all using (profile_id = auth.uid()) with check (profile_id = auth.uid());

drop policy if exists "life events owner access" on public.life_events;
create policy "life events owner access" on public.life_events
for all using (profile_id = auth.uid()) with check (profile_id = auth.uid());

drop policy if exists "activities owner access" on public.activities;
create policy "activities owner access" on public.activities
for all using (profile_id = auth.uid()) with check (profile_id = auth.uid());
